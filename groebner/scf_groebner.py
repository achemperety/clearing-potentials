def all_roots_real_large_z(g):
    """g: univariate polynomial over Q(z), squarefree.  True iff all its roots are real for every sufficiently large
    real z.  The number of real roots is constant for z beyond the real roots of disc(g)*lc(g); it is counted exactly
    by Sturm's theorem at a rational point beyond a Cauchy bound for those roots."""
    from fractions import Fraction
    from functools import reduce
    d = g.degree()
    if d <= 1:
        return True
    coeffs = [Kz(c) for c in g.list()]
    L = reduce(lambda x, y: x.lcm(y), [c.denominator() for c in coeffs])
    pc = [Rz(c * L) for c in coeffs]
    G = PolynomialRing(Rz, 'tt')(pc)
    crit = G.discriminant() * G.leading_coefficient()
    dc = [QQ(c) for c in crit.list()]
    while dc and dc[-1] == 0:
        dc.pop()
    if not dc:
        raise ValueError('polynomial not squarefree')
    bound = QQ(1) + (max(abs(c / dc[-1]) for c in dc[:-1]) if len(dc) > 1 else QQ(0))
    z0 = Fraction(int(bound.ceil()) + 1)
    vals = [Fraction(int(QQ(c(QQ(z0))).numerator()), int(QQ(c(QQ(z0))).denominator())) for c in pc]
    return sturm_count(vals) == d


def pendant_cycle_decide(m, counts, log=sys.stdout):
    """Decide all potentials of the directed m-cycle with counts[i] pendant vertices at c_i.

    Step 1: for every graph H on the pendant set P (up to rotations preserving the counts), the pendant
    identities (positions (W, v) with W inside P), saturated by the Phi(W) involved; minimal associated primes.
    Step 2: a component whose coordinates all have eliminants with only real roots for large real z is excluded by
    Theorem 6.3 (the cycle weights lie in Q(z) by Prop. 6.4).  Step 3: for the other components, the cycle weights
    are a(c_i) = z + (|N_U(c_i) & P| - r_i)/z; a backtracking over the cycle vertices c_0, c_1, ... assigns
    N_U(c_j) & P and the edges from c_j to c_0..c_{j-1}, and checks every identity at a position whose cycle part
    W & C has largest element c_j; an identity holds on the component iff its normal form modulo the prime is 0.
    Returns the list of survivors (complete graphs U on the component)."""
    from scf_core import cycle_with_pendants
    D = cycle_with_pendants(m, counts)
    n = D.n
    C = list(range(m))
    P = list(range(m, n))
    owner = {}
    v = m
    for i, c in enumerate(counts):
        for _ in range(c):
            owner[v] = i
            v += 1
    Cmask = (1 << m) - 1
    pos = sorted(D.reachable_positions())
    Rs = {q: to_sage(D.R(*q)) for q in pos}
    A = PolynomialRing(Kz, ['a%d' % p for p in P], order='degrevlex')
    ag = dict(zip(P, A.gens()))
    one = A(1)

    def rotmap(s):
        mp = {i: (i + s) % m for i in range(m)}
        byclass = {}
        for p in P:
            byclass.setdefault(owner[p], []).append(p)
        for i in range(m):
            for p, q in zip(byclass.get(i, []), byclass.get((i + s) % m, [])):
                mp[p] = q
        return mp
    rmaps = [rotmap(s) for s in range(m) if all(counts[(i + s) % m] == counts[i] for i in range(m))]
    Ppairs = [(x, y) for x in P for y in P if x < y]
    sub_pos = [q for q in pos if (q[0] & Cmask) == 0]
    seen = set()
    comps = []
    t0 = time.time()
    for mask in range(1 << len(Ppairs)):
        E = frozenset(Ppairs[k] for k in range(len(Ppairs)) if mask >> k & 1)
        if E in seen:
            continue
        for mp in rmaps:
            seen.add(frozenset(tuple(sorted((mp[x], mp[y]))) for x, y in E))
        adj = [0] * n
        for x, y in E:
            adj[x] |= 1 << y
            adj[y] |= 1 << x
        a = [A(0)] * n
        for p in P:
            a[p] = ag[p]
        mu = mu_factory_mask(adj, a, one)
        eqs, nz = [], set()
        for (W, v) in sub_pos:
            e = mu(W & ~(1 << v)) - A(Rs[(W, v)]) * mu(W)
            if e != 0:
                eqs.append(e)
            nz.add(W)
            nz.add(W & ~(1 << v))
        nzp = [mu(W) for W in nz]
        if any(f == 0 for f in nzp):
            continue
        J = A.ideal(eqs) if eqs else A.ideal([A(0)])
        if J.is_one():
            continue
        bad = False
        for f in sorted(set(nzp), key=lambda f: f.degree()):
            if f.is_constant():
                continue
            J = J.saturation(A.ideal([f]))[0]
            if J.is_one():
                bad = True
                break
        if bad:
            continue
        if J.dimension() != 0:
            print('positive-dimensional pendant component for H =', sorted(E), file=log, flush=True)
            comps.append((sorted(E), None))
            continue
        for Q in J.minimal_associated_primes():
            comps.append((sorted(E), Q))
    stats = {'components': len(comps), 'real': 0, 'nonreal': 0, 'killed_at_layer1': 0, 'nodes': 0}
    print('step 1: %d pairs (H, prime), %.0fs' % (len(comps), time.time() - t0), file=log, flush=True)
    layer = {j: [q for q in pos if (q[0] & Cmask) and ((q[0] & Cmask).bit_length() - 1) == j] for j in C}
    survivors = []
    for (E, Q) in comps:
        if Q is None:
            survivors.append((E, 'positive-dimensional'))
            continue
        gens = A.gens()
        real = True
        for k, g in enumerate(gens):
            others = [h for h in gens if h != g]
            el = Q.elimination_ideal(others).gens()
            el = [f for f in el if f != 0]
            if not el:
                real = False
                break
            f = el[0]
            uni = PolynomialRing(Kz, 'tt')
            gu = uni(f.polynomial(g)) if f.parent().ngens() > 1 else uni(f)
            if not all_roots_real_large_z(gu):
                real = False
                break
        if real:
            stats['real'] += 1
            continue
        stats['nonreal'] += 1
        # layer 1: neighbourhoods of single cycle vertices, positions with W & C = {c_j}
        single = {j: [q for q in pos if (q[0] & Cmask) == (1 << j)] for j in C}
        allowed = {}
        for j in C:
            ok = []
            for nbm in range(1 << len(P)):
                Nj = [P[k] for k in range(len(P)) if nbm >> k & 1]
                adj = [0] * n
                for x, y in E:
                    adj[x] |= 1 << y
                    adj[y] |= 1 << x
                for p in Nj:
                    adj[j] |= 1 << p
                    adj[p] |= 1 << j
                a = [A(0)] * n
                for p in P:
                    a[p] = ag[p]
                a[j] = A(Kz(zz) + (len(Nj) - counts[j]) / Kz(zz))
                mu = mu_factory_mask(adj, a, one)
                if all(Q.reduce(mu(W & ~(1 << v)) - A(Rs[(W, v)]) * mu(W)) == 0 for (W, v) in single[j]):
                    ok.append(Nj)
            allowed[j] = ok
        if any(not allowed[j] for j in C):
            stats['killed_at_layer1'] += 1
            continue
        # backtracking over cycle vertices
        def rec(j, Ns, cedges):
            if j == m:
                survivors.append((E, [list(x) for x in Ns], sorted(cedges)))
                print('SURVIVOR', E, Ns, sorted(cedges), file=log, flush=True)
                return
            for Nj in allowed[j]:
                for em in range(1 << j):
                    stats['nodes'] += 1
                    ce = cedges + [(i, j) for i in range(j) if em >> i & 1]
                    adj = [0] * n
                    for x, y in E:
                        adj[x] |= 1 << y
                        adj[y] |= 1 << x
                    for i, Ni in enumerate(Ns + [Nj]):
                        for p in Ni:
                            adj[i] |= 1 << p
                            adj[p] |= 1 << i
                    for x, y in ce:
                        adj[x] |= 1 << y
                        adj[y] |= 1 << x
                    a = [A(0)] * n
                    for p in P:
                        a[p] = ag[p]
                    for i, Ni in enumerate(Ns + [Nj]):
                        a[i] = A(Kz(zz) + (len(Ni) - counts[i]) / Kz(zz))
                    mu = mu_factory_mask(adj, a, one)
                    if all(Q.reduce(mu(W & ~(1 << v)) - A(Rs[(W, v)]) * mu(W)) == 0 for (W, v) in layer[j]):
                        rec(j + 1, Ns + [Nj], ce)
        rec(0, [], [])
    print('m=%d counts=%s: %s; survivors %d; %.0fs' % (m, counts, stats, len(survivors), time.time() - t0), file=log, flush=True)
    return survivors


def mu_factory_mask(adjmask, a, one):
    memo = {0: one}

    def mu(S):
        r = memo.get(S)
        if r is not None:
            return r
        v = (S & -S).bit_length() - 1
        rest = S & ~(1 << v)
        val = a[v] * mu(rest)
        nb = adjmask[v] & rest
        while nb:
            w = (nb & -nb).bit_length() - 1
            nb &= nb - 1
            val = val - mu(rest & ~(1 << w))
        memo[S] = val
        return val
    return mu


def digraph_automorphisms(D):
    """All automorphisms of a small digraph, by backtracking with in/out-degree pruning."""
    n = D.n
    outs = [set(bits(D.out[v])) for v in range(n)]
    ins = [set(bits(D.inn[v])) for v in range(n)]
    sig = [(len(outs[v]), len(ins[v]), len(outs[v] & ins[v])) for v in range(n)]
    res = []
    perm = [-1] * n
    used = [False] * n

    def ok(v, w):
        for u in range(v):
            pu = perm[u]
            if (u in outs[v]) != (pu in outs[w]) or (u in ins[v]) != (pu in ins[w]):
                return False
        return True

    def rec(v):
        if v == n:
            res.append(tuple(perm))
            return
        for w in range(n):
            if not used[w] and sig[w] == sig[v] and ok(v, w):
                perm[v] = w
                used[w] = True
                rec(v + 1)
                used[w] = False
        perm[v] = -1
    rec(0)
    return res


def branch_cycle_decide(D, m, log=sys.stdout, progress=0):
    """Decide all potentials of a digraph D made of the directed cycle 0 -> 1 -> ... -> m-1 -> 0 and symmetric
    trees hanging at cycle vertices (branch vertices B = {m, ..., n-1}).

    Step 1: for every graph H on B (up to automorphisms of D fixing B setwise), the identities at the reachable
    positions (W, v) with W inside B (the play has visited the whole cycle), saturated; minimal associated primes.
    Step 2: if every coordinate of a component has an eliminant with only real roots for large real z, all weights
    are real (the cycle weights below are rational functions of the branch weights) and Theorem 6.3 excludes it.
    Step 3: otherwise, in the field A/Q, the weight of c_j is fixed by the cavity identity at the reachable
    position (B + c_j, c_j) (the play around the cycle ending at c_j), given N_U(c_j) & B; a backtracking over
    c_0, c_1, ... assigns N_U(c_j) & B and the edges from c_j to c_0..c_{j-1} and checks every identity at a
    position whose cycle part has largest element c_j.  Identities are tested by exact arithmetic in A/Q.
    A survivor would still have to be checked for the non-vanishing conditions of Theorem 6.7 before it counts as
    a potential; in every case run here there is no survivor, so that check never arises."""
    n = D.n
    C = list(range(m))
    B = list(range(m, n))
    Cmask = (1 << m) - 1
    Bmask = D.full & ~Cmask
    pos = sorted(D.reachable_positions())
    Rs = {q: to_sage(D.R(*q)) for q in pos}
    A = PolynomialRing(Kz, ['a%d' % p for p in B], order='degrevlex')
    ag = dict(zip(B, A.gens()))
    one = A(1)
    auts = [p for p in digraph_automorphisms(D) if all(p[v] >= m for v in B)]
    Bpairs = [(x, y) for x in B for y in B if x < y]
    sub_pos = [q for q in pos if (q[0] & Cmask) == 0]
    seen = set()
    comps = []
    t0 = time.time()
    nH = 0
    for mask in range(1 << len(Bpairs)):
        E = frozenset(Bpairs[k] for k in range(len(Bpairs)) if mask >> k & 1)
        if E in seen:
            continue
        for p in auts:
            seen.add(frozenset(tuple(sorted((p[x], p[y]))) for x, y in E))
        nH += 1
        if progress and nH % progress == 0:
            print('... %d graphs H, %d components so far, %.0fs' % (nH, len(comps), time.time() - t0), file=log, flush=True)
        adj = [0] * n
        for x, y in E:
            adj[x] |= 1 << y
            adj[y] |= 1 << x
        a = [A(0)] * n
        for b in B:
            a[b] = ag[b]
        mu = mu_factory_mask(adj, a, one)
        eqs, nz = [], set()
        for (W, v) in sub_pos:
            e = mu(W & ~(1 << v)) - A(Rs[(W, v)]) * mu(W)
            if e != 0:
                eqs.append(e)
            nz.add(W)
            nz.add(W & ~(1 << v))
        nzp = [mu(W) for W in nz]
        if any(f == 0 for f in nzp):
            continue
        J = A.ideal(eqs) if eqs else A.ideal([A(0)])
        if J.is_one():
            continue
        bad = False
        for f in sorted(set(nzp), key=lambda f: f.degree()):
            if f.is_constant():
                continue
            J = J.saturation(A.ideal([f]))[0]
            if J.is_one():
                bad = True
                break
        if bad:
            continue
        if J.dimension() != 0:
            print('positive-dimensional branch component for H =', sorted(E), file=log, flush=True)
            comps.append((sorted(E), None))
            continue
        for Q in J.minimal_associated_primes():
            comps.append((sorted(E), Q))
    stats = {'components': len(comps), 'real': 0, 'nonreal': 0, 'killed_at_layer1': 0, 'layer1_empty_at': {}, 'nodes': 0}
    print('step 1: %d graphs H up to symmetry, %d pairs (H, prime), %.0fs' % (nH, len(comps), time.time() - t0), file=log, flush=True)
    if len(comps) <= 12:
        for (E, Q) in comps:
            print('   H = %s: %s' % (E, 'positive-dimensional' if Q is None else 'prime generated by ' + str(list(Q.gens()))), file=log, flush=True)
    layer = {j: [q for q in pos if (q[0] & Cmask) and ((q[0] & Cmask).bit_length() - 1) == j] for j in C}
    single = {j: [q for q in pos if (q[0] & Cmask) == (1 << j)] for j in C}
    survivors = []
    uni = PolynomialRing(Kz, 'tt')
    for (E, Q) in comps:
        if Q is None:
            survivors.append((E, 'positive-dimensional'))
            continue
        real = True
        for g in A.gens():
            others = [h for h in A.gens() if h != g]
            el = [f for f in Q.elimination_ideal(others).gens() if f != 0]
            if not el or not all_roots_real_large_z(uni(el[0].polynomial(g))):
                real = False
                break
        if real:
            stats['real'] += 1
            continue
        stats['nonreal'] += 1
        Rq = A.quotient(Q)
        adjB = [0] * n
        for x, y in E:
            adjB[x] |= 1 << y
            adjB[y] |= 1 << x
        aB = [Rq(0)] * n
        for b in B:
            aB[b] = Rq(ag[b])
        muB = mu_factory_mask(adjB, aB, Rq(1))
        PhiB = muB(Bmask)
        invPhiB = PhiB ** -1

        def cycle_weight(j, Nj):
            val = Rq(Kz(zz))
            outs = set(bits(D.out[j]))
            for w in set(Nj) - outs:
                val += muB(Bmask & ~(1 << w)) * invPhiB
            for t in (outs & set(B)) - set(Nj):
                val -= Rq(Rs[(Bmask, t)]) if (Bmask, t) in Rs else Rq(to_sage(D.R(Bmask, t)))
            return val

        def check(Ns, cedges, plist):
            adj = list(adjB)
            for i, Ni in enumerate(Ns):
                for p in Ni:
                    adj[i] |= 1 << p
                    adj[p] |= 1 << i
            for x, y in cedges:
                adj[x] |= 1 << y
                adj[y] |= 1 << x
            a = list(aB)
            for i, Ni in enumerate(Ns):
                a[i] = cycle_weight(i, Ni)
            mu = mu_factory_mask(adj, a, Rq(1))
            return all(mu(W & ~(1 << v)) - Rq(Rs[(W, v)]) * mu(W) == 0 for (W, v) in plist)

        allowed = {}
        for j in C:
            ok = []
            for nbm in range(1 << len(B)):
                Nj = [B[k] for k in range(len(B)) if nbm >> k & 1]
                Ns = [[] for _ in range(j)] + [Nj]
                # only c_j's neighbourhood matters for positions with cycle part {c_j}
                adj = list(adjB)
                for p in Nj:
                    adj[j] |= 1 << p
                    adj[p] |= 1 << j
                a = list(aB)
                a[j] = cycle_weight(j, Nj)
                mu = mu_factory_mask(adj, a, Rq(1))
                if all(mu(W & ~(1 << v)) - Rq(Rs[(W, v)]) * mu(W) == 0 for (W, v) in single[j]):
                    ok.append(Nj)
            allowed[j] = ok
        if any(not allowed[j] for j in C):
            stats['killed_at_layer1'] += 1
            for j in C:
                if not allowed[j]:   # cycle vertex c_j admits no neighbourhood in B on this component
                    stats['layer1_empty_at'][j] = stats['layer1_empty_at'].get(j, 0) + 1
            continue

        def rec(j, Ns, cedges):
            if j == m:
                survivors.append((E, [list(x) for x in Ns], sorted(cedges)))
                print('SURVIVOR', E, Ns, sorted(cedges), file=log, flush=True)
                return
            for Nj in allowed[j]:
                for em in range(1 << j):
                    stats['nodes'] += 1
                    ce = cedges + [(i, j) for i in range(j) if em >> i & 1]
                    if check(Ns + [Nj], ce, layer[j]):
                        rec(j + 1, Ns + [Nj], ce)
        rec(0, [], [])
    print('%s: %s; survivors %d; %.0fs' % (D.arcs if n <= 6 else 'n=%d' % n, stats, len(survivors), time.time() - t0), file=log, flush=True)
    return survivors


class BranchGraphDecider:
    """Theorem 6.7 restricted to one graph H on the branch vertices (the procedure treats the pairs (H, Q)
    independently, so running it graph by graph gives the same decision as branch_cycle_decide).

    With reduce=True (the directed triangle with pendant classes of size <= 2) the branch weights are first fixed by
    Lemma 6.8: a_u = z + d_u/z if u has no H-neighbour in its own class, and a_u' = a_u + (d_u' - d_u)/z if the two
    pendant vertices u, u' of a class are adjacent in H (d_u = number of H-neighbours of u in other classes).  These
    relations hold in every potential, so the substitution loses no solution and the components correspond."""

    def __init__(self, D, m, reduce=False):
        self.D, self.m = D, m
        n = D.n
        self.C = list(range(m))
        self.B = list(range(m, n))
        self.Cmask = (1 << m) - 1
        self.Bmask = D.full & ~self.Cmask
        self.pos = sorted(D.reachable_positions())
        self.Rs = {q: to_sage(D.R(*q)) for q in self.pos}
        self.sub_pos = [q for q in self.pos if (q[0] & self.Cmask) == 0]
        self.layer = {j: [q for q in self.pos if (q[0] & self.Cmask) and ((q[0] & self.Cmask).bit_length() - 1) == j] for j in self.C}
        self.single = {j: [q for q in self.pos if (q[0] & self.Cmask) == (1 << j)] for j in self.C}
        self.uni = PolynomialRing(Kz, 'tt')
        self.classes = None
        if reduce:
            assert m == 3, 'Lemma 6.8 is stated for the directed triangle'
            owner = {b: [c for c in bits(D.out[b]) if c < m] for b in self.B}
            assert all(len(o) == 1 and D.out[b] == 1 << o[0] for b, o in owner.items()), 'pendant vertices only'
            cls = {}
            for b in self.B:
                cls.setdefault(owner[b][0], []).append(b)
            assert all(len(c) <= 2 for c in cls.values())
            self.classes = list(cls.values())

    def ring_and_weights(self, Es):
        n = self.D.n
        if self.classes is None:
            A = PolynomialRing(Kz, len(self.B), ['a%d' % b for b in self.B], order='degrevlex')
            a = [A(0)] * n
            for b, g in zip(self.B, A.gens()):
                a[b] = g
            return A, a, list(A.gens())
        cl = {}
        for c in self.classes:
            for u in c:
                cl[u] = tuple(c)
        d = {u: sum(1 for (x, y) in Es if u in (x, y) and cl[x] != cl[y]) for u in self.B}
        free = [c[0] for c in self.classes if len(c) == 2 and tuple(sorted(c)) in Es]
        names = ['a%d' % u for u in free] or ['dummy']
        A = PolynomialRing(Kz, len(names), names, order='degrevlex')   # multivariate even with one variable
        g = dict(zip(free, A.gens()))
        a = [A(0)] * n
        for c in self.classes:
            if c[0] in g:
                a[c[0]] = g[c[0]]
                a[c[1]] = g[c[0]] + A(Kz(d[c[1]] - d[c[0]]) / Kz(zz))
            else:
                for u in c:
                    a[u] = A(Kz(zz) + Kz(d[u]) / Kz(zz))
        return A, a, [g[u] for u in free]

    def decide(self, E):
        """Returns (statistics, survivors, outcome) for the graph H with edge list E."""
        D, n, B, C, Bmask, Rs = self.D, self.D.n, self.B, self.C, self.Bmask, self.Rs
        stats = {'components': 0, 'real': 0, 'nonreal': 0, 'killed_at_layer1': 0, 'layer1_empty_at': {}, 'nodes': 0}
        Es = set(tuple(sorted(e)) for e in E)
        adj = [0] * n
        for x, y in Es:
            adj[x] |= 1 << y
            adj[y] |= 1 << x
        A, a, gens = self.ring_and_weights(Es)
        mu = mu_factory_mask(adj, a, A(1))
        eqs, nz = [], set()
        for (W, v) in self.sub_pos:
            e = mu(W & ~(1 << v)) - A(Rs[(W, v)]) * mu(W)
            if e != 0:
                eqs.append(e)
            nz.add(W)
            nz.add(W & ~(1 << v))
        nzp = [mu(W) for W in nz]
        if any(f == 0 for f in nzp):
            return stats, [], 'some Phi(W) vanishes'
        if any(e.is_constant() for e in eqs):
            return stats, [], 'unit ideal'
        if not gens:
            stats['components'] = stats['real'] = 1      # all branch weights in Q(z) and all branch identities hold
            return stats, [], 'one rational point'
        J = A.ideal(eqs) if eqs else A.ideal([A(0)])
        if J.is_one():
            return stats, [], 'unit ideal'
        for f in sorted(set(nzp), key=lambda f: f.degree()):
            if f.is_constant():
                continue
            J = J.saturation(A.ideal([f]))[0]
            if J.is_one():
                return stats, [], 'unit ideal after saturation'
        if J.dimension() != 0:
            return stats, [(sorted(Es), 'positive-dimensional')], 'positive-dimensional'
        comps = J.minimal_associated_primes()
        self.last_primes = comps
        stats['components'] = len(comps)
        survivors = []
        for Q in comps:
            real = True
            for g in gens:
                others = [h for h in A.gens() if h != g]
                el = [f for f in Q.elimination_ideal(others).gens() if f != 0]
                if not el or not all_roots_real_large_z(self.uni(el[0].univariate_polynomial().list())):
                    real = False
                    break
            if real:
                stats['real'] += 1
                continue
            stats['nonreal'] += 1
            Rq = A.quotient(Q)
            aB = [Rq(0)] * n
            for b in B:
                aB[b] = Rq(a[b])
            muB = mu_factory_mask(adj, aB, Rq(1))
            invPhiB = muB(Bmask) ** -1

            def cycle_weight(j, Nj):
                val = Rq(Kz(zz))
                outs = set(bits(D.out[j]))
                for w in set(Nj) - outs:
                    val += muB(Bmask & ~(1 << w)) * invPhiB
                for t in (outs & set(B)) - set(Nj):
                    val -= Rq(Rs[(Bmask, t)]) if (Bmask, t) in Rs else Rq(to_sage(D.R(Bmask, t)))
                return val

            def check(Ns, cedges, plist):
                ad = list(adj)
                for i, Ni in enumerate(Ns):
                    for p in Ni:
                        ad[i] |= 1 << p
                        ad[p] |= 1 << i
                for x, y in cedges:
                    ad[x] |= 1 << y
                    ad[y] |= 1 << x
                aa = list(aB)
                for i, Ni in enumerate(Ns):
                    aa[i] = cycle_weight(i, Ni)
                mu2 = mu_factory_mask(ad, aa, Rq(1))
                return all(mu2(W & ~(1 << v)) - Rq(Rs[(W, v)]) * mu2(W) == 0 for (W, v) in plist)

            allowed = {}
            for j in C:
                ok = []
                for nbm in range(1 << len(B)):
                    Nj = [B[k] for k in range(len(B)) if nbm >> k & 1]
                    if check([[] for _ in range(j)] + [Nj], [], self.single[j]):
                        ok.append(Nj)
                allowed[j] = ok
            if any(not allowed[j] for j in C):
                stats['killed_at_layer1'] += 1
                for j in C:
                    if not allowed[j]:
                        stats['layer1_empty_at'][j] = stats['layer1_empty_at'].get(j, 0) + 1
                continue

            def rec(j, Ns, cedges):
                if j == self.m:
                    survivors.append((sorted(Es), [list(x) for x in Ns], sorted(cedges)))
                    return
                for Nj in allowed[j]:
                    for em in range(1 << j):
                        stats['nodes'] += 1
                        ce = cedges + [(i, j) for i in range(j) if em >> i & 1]
                        if check(Ns + [Nj], ce, self.layer[j]):
                            rec(j + 1, Ns + [Nj], ce)
            rec(0, [], [])
        return stats, survivors, 'components'


def branch_graph_reps(D, m):
    """The graphs H on the branch vertices up to the automorphisms of D fixing them, in the order of branch_cycle_decide."""
    B = list(range(m, D.n))
    auts = [p for p in digraph_automorphisms(D) if all(p[v] >= m for v in B)]
    Bpairs = [(x, y) for x in B for y in B if x < y]
    seen, reps = set(), []
    for mask in range(1 << len(Bpairs)):
        E = frozenset(Bpairs[k] for k in range(len(Bpairs)) if mask >> k & 1)
        if E in seen:
            continue
        for p in auts:
            seen.add(frozenset(tuple(sorted((p[x], p[y]))) for x, y in E))
        reps.append(sorted(E))
    return reps, len(auts)


def triangle_pendants_decide(counts, log=sys.stdout, compare=0):
    """Theorem 6.7 for the directed triangle with counts[i] <= 2 pendant vertices at c_i, graph by graph, with the
    reduction of Lemma 6.8.  With compare=N the unreduced decision is also run on the first N graphs H and the
    numbers of components are compared."""
    from scf_core import cycle_with_pendants
    D = cycle_with_pendants(3, counts)
    reps, naut = branch_graph_reps(D, 3)
    red = BranchGraphDecider(D, 3, reduce=True)
    plain = BranchGraphDecider(D, 3) if compare else None
    t0 = time.time()
    tot = {'components': 0, 'real': 0, 'nonreal': 0, 'killed_at_layer1': 0, 'layer1_empty_at': {}, 'nodes': 0}
    outcomes, survivors, agree = {}, [], 0
    for k, E in enumerate(reps):
        st, sv, why = red.decide(E)
        outcomes[why] = outcomes.get(why, 0) + 1
        for key in ('components', 'real', 'nonreal', 'killed_at_layer1', 'nodes'):
            tot[key] += st[key]
        for j, c in st['layer1_empty_at'].items():
            tot['layer1_empty_at'][j] = tot['layer1_empty_at'].get(j, 0) + c
        survivors += sv
        if st['components']:
            print('   H = %s: %d component(s), %d real' % (E, st['components'], st['real']), file=log, flush=True)
            if why == 'components':
                for Q in red.last_primes:
                    print('      prime generated by %s' % list(Q.gens()), file=log, flush=True)
        if k < compare:
            st2 = plain.decide(E)[0]
            agree += (st2['components'], st2['real'], st2['nonreal']) == (st['components'], st['real'], st['nonreal'])
    print('graphs H up to the %d automorphisms fixing the pendant vertices: %d; outcomes %s' % (naut, len(reps), outcomes), file=log)
    if compare:
        print('unreduced decision on the first %d graphs H: same components on %d' % (min(compare, len(reps)), agree), file=log)
    print('n=%d: %s; survivors %d; %.0fs' % (D.n, tot, len(survivors), time.time() - t0), file=log, flush=True)
    return survivors


