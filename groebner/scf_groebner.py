#!/usr/bin/env python3
"""Optional exact Groebner computations over Q(z) for Section 6 of the paper (requires passagemath-singular).

    pip install --break-system-packages passagemath-singular

Usage:
    python3 scf_groebner.py report                       short cross-checks (about 1 minute)
    python3 scf_groebner.py search '<json spec>' [mode]  all graphs U up to Aut(D) for one digraph;
                                                         mode = plain (default) or clearing
    python3 scf_groebner.py symmetric N                  uniqueness of potentials on connected graphs, n <= N
    python3 scf_groebner.py pendants m r0,r1,...         all potentials of C_m with r_i pendant vertices at c_i
                                                         (pendant graphs H up to rotation only)
    python3 scf_groebner.py branches-pendants m r0,...   the same by the general procedure of Theorem 6.7
                                                         (H up to all automorphisms of D fixing the branches)
    python3 scf_groebner.py legs m l0,l1,...             C_m with a symmetric leg of length l_i at c_i (Theorem 6.7)
    python3 scf_groebner.py triangle-pendants r0,r1,r2 [N]   C_3 with r_i <= 2 pendant vertices at c_i, graph by graph,
                                                         with the reduction of Lemma 6.8 (and the unreduced
                                                         decision on the first N graphs H for comparison)

A potential with graph U exists over some field iff the ideal generated by the identities
Phi(W - v) - R(W, v) Phi(W) at reachable positions, saturated by every Phi(W), is not the unit
ideal of Q(z)[a] [ALC, Lemma 10.1 and Thm 10.15].  In mode 'clearing' the weights of the vertices
cleared by path sets are first fixed by the cavity identity (Lemma 3.3), which is a consequence of the
same identities, and the remaining unknowns are decided as before.
"""
import itertools, json, os, sys, time
from fractions import Fraction

from sage.all__sagemath_singular import PolynomialRing, QQ, FractionField

from scf_core import Digraph, bits, popcount, sturm_count

Rz = PolynomialRing(QQ, 'z')
zz = Rz.gen()
Kz = FractionField(Rz)


def to_sage(rf):
    num = sum(QQ(c) * zz ** i for i, c in enumerate(rf.num))
    den = sum(QQ(c) * zz ** i for i, c in enumerate(rf.den))
    return Kz(num) / Kz(den)


def mu_factory(U, n, a, one):
    adj = [[] for _ in range(n)]
    for (i, j) in U:
        adj[i].append(j)
        adj[j].append(i)
    memo = {0: one}

    def mu(S):
        if S in memo:
            return memo[S]
        v = (S & -S).bit_length() - 1
        rest = S & ~(1 << v)
        val = a[v] * mu(rest)
        for w in adj[v]:
            if rest >> w & 1:
                val = val - mu(rest & ~(1 << w))
        memo[S] = val
        return val
    return mu


class Decider:
    def __init__(self, D):
        self.D = D
        self.pos = sorted(D.reachable_positions())
        self.Rs = {p: to_sage(D.R(*p)) for p in self.pos}
        self.Phi = D.set_potential()
        can = D.path_table()
        self.cpos = {x: [] for x in range(D.n)}
        for S in range(1, D.full + 1):
            for x in bits(can[S]):
                rest = D.full & ~S
                if all(can[S | (1 << w)] for w in bits(rest & ~D.out[x])):
                    self.cpos[x].append(S)
        self.Phis = None if self.Phi is None else {k: to_sage(v) for k, v in self.Phi.items()}

    def cleared_weights(self, U):
        """Values of a_x forced by the cavity identity at every basic clearing position (Lemma 3.3)."""
        D = self.D
        adj = [set() for _ in range(D.n)]
        for (i, j) in U:
            adj[i].add(j)
            adj[j].add(i)
        vals = {}
        for x, Ss in self.cpos.items():
            if not Ss:
                continue
            outs = set(bits(D.out[x]))
            vs = set()
            for S in Ss:
                rest = D.full & ~S
                val = Kz(zz)
                for w in adj[x] - outs:
                    if rest >> w & 1:
                        val += self.Phis[rest & ~(1 << w)] / self.Phis[rest]
                for t in outs - adj[x]:
                    if rest >> t & 1:
                        val -= to_sage(D.R(rest, t))
                vs.add(val)
            vals[x] = vs
        return vals

    def decide(self, U, mode='plain'):
        D = self.D
        n = D.n
        fixed = {}
        if mode == 'clearing':
            if self.Phi is None:
                return False, 'no set potential'
            for x, vs in self.cleared_weights(U).items():
                if len(vs) > 1:
                    return False, 'cavity values disagree'
                fixed[x] = next(iter(vs))
        free = [v for v in range(n) if v not in fixed]
        A = PolynomialRing(Kz, ['a%d' % i for i in free] or ['dummy'], order='degrevlex')
        g = dict(zip(free, A.gens()))
        a = [g[v] if v in g else A(fixed[v]) for v in range(n)]
        mu = mu_factory(U, n, a, A(1))
        eqs, Ws = [], set()
        for (W, v) in self.pos:
            e = mu(W & ~(1 << v)) - A(self.Rs[(W, v)]) * mu(W)
            if e != 0:
                eqs.append(e)
            Ws.add(W)
            Ws.add(W & ~(1 << v))
        nz = [mu(W) for W in Ws]
        if any(f == 0 for f in nz):
            return False, 'some Phi(W) vanishes'
        if not eqs:
            return True, 'all identities hold'
        J = A.ideal(eqs)
        if J.is_one():
            return False, 'unit ideal'
        for f in sorted(set(nz), key=lambda f: f.degree()):
            if f.is_constant():
                continue
            J = J.saturation(A.ideal([f]))[0]
            if J.is_one():
                return False, 'unit ideal after saturation'
        return True, 'potential exists'

    def forced_standard(self, U):
        """For a symmetric digraph and U = G: is a = z forced (a_x - z in the radical)?"""
        D = self.D
        n = D.n
        A = PolynomialRing(Kz, ['a%d' % i for i in range(n)], order='degrevlex')
        a = A.gens()
        mu = mu_factory(U, n, a, A(1))
        eqs, Ws = [], set()
        for (W, v) in self.pos:
            e = mu(W & ~(1 << v)) - A(self.Rs[(W, v)]) * mu(W)
            if e != 0:
                eqs.append(e)
            Ws.add(W)
            Ws.add(W & ~(1 << v))
        J = A.ideal(eqs)
        for f in sorted(set(mu(W) for W in Ws), key=lambda f: f.degree()):
            if not f.is_constant():
                J = J.saturation(A.ideal([f]))[0]
        if J.is_one():
            return None
        rad = J.radical()
        return all((a[i] - A(zz)) in rad for i in range(n))


def automorphisms(D):
    s = set(D.arcs)
    return [p for p in itertools.permutations(range(D.n)) if all((p[a], p[b]) in s for a, b in D.arcs)]


def orbit_reps(n, auts):
    pairs = [(i, j) for i in range(n) for j in range(i + 1, n)]
    idx = {p: k for k, p in enumerate(pairs)}
    maps = [[idx[(min(p[i], p[j]), max(p[i], p[j]))] for (i, j) in pairs] for p in auts]
    E = len(pairs)
    seen = bytearray(1 << E)
    for mask in range(1 << E):
        if seen[mask]:
            continue
        bs = [k for k in range(E) if mask >> k & 1]
        for mp in maps:
            m2 = 0
            for k in bs:
                m2 |= 1 << mp[k]
            seen[m2] = 1
        yield [pairs[k] for k in bs]


def prune_ok(D, U):
    """Field-independent necessary conditions: locality [ALC Thm 10.8] and no phantom [ALC Thm 10.6]."""
    n = D.n
    reach = [D.reach(v) for v in range(n)]
    adj = [0] * n
    for (i, j) in U:
        adj[i] |= 1 << j
        adj[j] |= 1 << i
    comp = [0] * n
    for v in range(n):
        seen, fr = 1 << v, 1 << v
        while fr:
            x = (fr & -fr).bit_length() - 1
            fr &= fr - 1
            new = adj[x] & ~seen
            seen |= new
            fr |= new
        comp[v] = seen
    for u in range(n):
        for v in range(n):
            if (reach[u] >> v & 1) and (reach[v] >> u & 1) and not (comp[u] >> v & 1):
                return False
    for v in range(n):
        if adj[v] & ~D.out[v] == 0:
            for t in bits(D.out[v] & ~adj[v]):
                if reach[t] >> v & 1:
                    return False
    return True


def search(D, mode='plain', log=None):
    dec = Decider(D)
    auts = automorphisms(D)
    t = time.time()
    tested = positive = 0
    reasons = {}
    pos = []
    for U in orbit_reps(D.n, auts):
        if not prune_ok(D, U):
            continue
        tested += 1
        ok, why = dec.decide(U, mode)
        reasons[why] = reasons.get(why, 0) + 1
        if ok:
            positive += 1
            pos.append(U)
        if log and tested % 1000 == 0:
            print('...', tested, positive, round(time.time() - t), file=log, flush=True)
    return {'arcs': D.arcs, 'auts': len(auts), 'tested': tested, 'positive': pos, 'reasons': reasons,
            'time': round(time.time() - t, 1)}


def symmetric_uniqueness(nmax):
    import networkx as nx
    from networkx.generators.atlas import graph_atlas_g
    out = []
    for G in graph_atlas_g():
        n = G.number_of_nodes()
        if n < 2 or n > nmax or not nx.is_connected(G):
            continue
        D = Digraph(n, [(i, j) for i, j in G.edges()] + [(j, i) for i, j in G.edges()])
        dec = Decider(D)
        Gset = set(tuple(sorted(e)) for e in G.edges())
        others = [U for U in orbit_reps(n, automorphisms(D)) if prune_ok(D, U) and set(U) != Gset and dec.decide(U)[0]]
        out.append((n, sorted(Gset), others, dec.forced_standard(sorted(Gset))))
    return out


def run_report():
    t = time.time()
    res = symmetric_uniqueness(4)
    print('connected graphs on at most 4 vertices: %d; other graphs U with a potential: %d; a = z forced for U = G: %s  (%.0fs)' % (
        len(res), sum(len(r[2]) for r in res), all(r[3] for r in res), time.time() - t))
    # the clearing substitution against the plain decision on a sample of graphs U
    from scf_core import cycle_with_pendants, blowup
    for name, D in [('C3 with one pendant per vertex', cycle_with_pendants(3, [1, 1, 1])),
                    ('C4(1,2,1,2)', blowup([1, 2, 1, 2])[0])]:
        dec = Decider(D)
        t = time.time()
        reps = [U for U in orbit_reps(D.n, automorphisms(D)) if prune_ok(D, U)]
        sample = reps[::max(1, len(reps) // 150)]
        agree = sum(dec.decide(U, 'plain')[0] == dec.decide(U, 'clearing')[0] for U in sample)
        pos = sum(dec.decide(U, 'clearing')[0] for U in sample)
        print('%s: %d graphs U up to symmetry after pruning; sample of %d: plain and clearing decisions agree on %d, potentials found %d  (%.0fs)' % (
            name, len(reps), len(sample), agree, pos, time.time() - t))
    print('full searches: logs/groebner_*.txt')



